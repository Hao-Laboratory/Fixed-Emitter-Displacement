function [results, truth, trajectoryFig] = example_run()
%EXAMPLE_RUN Generate 25 demonstration frames and plot their estimated drift.
% Images and truth.mat are saved in a new temporary directory.
params = struct( ...
    'dataDir', tempname, ...
    'ext', '*.tif', ...
    'pixelSizeNm', 61.9, ...
    'maxFramesOverride', [], ...
    'numericType', 'double', ...
    'localizeMethod', 'matlab', ...
    'returnQuality', false, ...
    'enableLocalizeProfile', false, ...
    'detectThresh', [], ...
    'kSigma', 6, ...
    'thresholdMethod', 'sampled', ...
    'thresholdSampleStride', 4, ...
    'detectThreshRefresh', 1, ...
    'localMaxWindowPx', 3, ...
    'R', 3, ...
    'maxMatchDist', 0.2, ...
    'madTau', 3, ...
    'templateMinAppearFrames', 3, ...
    'templateSigmaKeepFrac', 0.85, ...
    'templateDnnMinPxWhenMinSepOff', 6, ...
    'templateUpdateMatchFrac', 0.83, ...
    'templateUpdateInterval', 150, ...
    'templateBridgeMatchDist', 2, ...
    'templateBridgeMinCommonPoints', 50, ...
    'templateUpdateMode', "prev5_then_current_frame", ...
    'verbose', false, ...
    'printTimingSummary', false, ...
    'printCompletionMessage', true);

